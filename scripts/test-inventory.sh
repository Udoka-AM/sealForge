#!/usr/bin/env bash
# Regenerate docs/evidence/test-inventory.md from real test output.
# Counts come from the test runners, never by hand.
#
# Needs DATABASE_URL pointing at a Postgres server (sqlx::test creates a fresh
# database per integration test), as in CI:
#   docker compose -f infra/docker-compose.yml up -d postgres
#   DATABASE_URL=postgres://sealforge:sealforge@127.0.0.1:5432/sealforge scripts/test-inventory.sh
set -euo pipefail
cd "$(dirname "$0")/.."

: "${DATABASE_URL:?set DATABASE_URL (see the comment at the top of this script)}"
out=docs/evidence/test-inventory.md
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cargo test --workspace --no-fail-fast -- --format=terse >"$tmp/cargo.log" 2>&1 || {
  echo "cargo test failed; see output below" >&2
  tail -50 "$tmp/cargo.log" >&2
  exit 1
}
pnpm test >"$tmp/pnpm.log" 2>&1 || {
  echo "pnpm test failed" >&2
  tail -50 "$tmp/pnpm.log" >&2
  exit 1
}
# Per-test names for the Rust suites.
cargo test --workspace -- --list --format=terse >"$tmp/list.log" 2>&1 || true

commit=$(git rev-parse --short HEAD)
dirty=$(git diff --quiet HEAD -- crates tools packages apps || echo " (with uncommitted changes)")

{
  echo "# Test inventory"
  echo
  echo "Generated by \`scripts/test-inventory.sh\` on $(date -u +%Y-%m-%d) at commit \`$commit\`$dirty. Do not edit by hand."
  echo
  echo "## Totals"
  echo
  rust_total=$(awk '/^test result:/ {n += $4} END {print n + 0}' "$tmp/cargo.log")
  rust_failed=$(awk '/^test result:/ {n += $6} END {print n + 0}' "$tmp/cargo.log")
  ts_total=$(sed 's/\x1b\[[0-9;]*m//g' "$tmp/pnpm.log" | awk '/Tests +[0-9]+ passed/ {for (i = 1; i <= NF; i++) if ($i == "passed") n += $(i-1)} END {print n + 0}')
  echo "| Suite | Passed | Failed |"
  echo "|---|---|---|"
  echo "| Rust (\`cargo test --workspace\`) | $rust_total | $rust_failed |"
  echo "| TypeScript (\`pnpm test\`) | $ts_total | 0 |"
  echo
  echo "## Rust, by test binary"
  echo
  echo "| Tests | Binary |"
  echo "|---|---|"
  # "Running tests/api.rs (target/debug/deps/api-<hash>)" -> crate dir + target.
  awk -F'[()]' '/Running/ {src = $1; sub(/^ *Running */, "", src); sub(/ *$/, "", src); bin = $2; sub(/^.*\//, "", bin); sub(/-[0-9a-f]+$/, "", bin); label = bin " (" src ")"}
       /^test result:/ {split($0, f, " "); if (f[4] > 0) printf "| %s | `%s` |\n", f[4], label}' "$tmp/cargo.log"
  echo
  echo "## Rust test names"
  echo
  awk -F'[()]' '/Running/ {bin = $2; sub(/^.*\//, "", bin); sub(/-[0-9a-f]+$/, "", bin)}
       /: test$/ {name = $0; sub(/: test$/, "", name); print bin "\t" name}' "$tmp/list.log" |
    sort | awk -F'\t' '$1 != cur {if (cur != "") print "```\n"; cur = $1; print "**`" cur "`**\n\n```text"} {print $2} END {if (cur != "") print "```"}'
  echo
  echo "## TypeScript, by package"
  echo
  sed 's/\x1b\[[0-9;]*m//g' "$tmp/pnpm.log" | awk '/Tests +[0-9]+ passed/ {pkg = $1; for (i = 1; i <= NF; i++) if ($i == "passed") printf "- `%s`: %s passed\n", pkg, $(i-1)}'
} >"$out"

echo "wrote $out"
